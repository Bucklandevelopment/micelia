class TestTunnelServiceIntegration:

    @pytest.mark.asyncio
    async def test_full_lifecycle_start_info_stop(self, service):
        """Full lifecycle: start -> get_info -> stop -> get_info."""
        mock_tunnel = _make_tunnel_obj("https://lifecycle.ngrok.io")
        modules, mock_ngrok, _ = _mock_pyngrok()
        mock_ngrok.connect.return_value = mock_tunnel
        mock_ngrok.get_tunnels.return_value = [mock_tunnel]

        # Start
        with patch.dict(sys.modules, modules):
            with patch("app.services.tunnel.settings") as s:
                s.gateway_port = 8888
                s.ngrok_authtoken = ""
                s.ngrok_domain = None
                url = await service.start()

        assert url == "https://lifecycle.ngrok.io"
        assert service.is_connected is True

        # Get info while connected
        with patch.dict(sys.modules, modules):
            info = service.get_info()
        assert info["connected"] is True
        assert info["tunnels_count"] == 1

        # Stop
        with patch.dict(sys.modules, modules):
            await service.stop()

        assert service.is_connected is False

        # Get info after stop
        info_after = service.get_info()
        assert info_after["connected"] is False
        assert info_after["public_url"] is None
