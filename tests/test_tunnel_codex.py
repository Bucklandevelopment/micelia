    def test_get_info_when_connected_with_tunnels(self, service):
        modules, mock_ngrok, _ = _mock_pyngrok()
        service._connected = True
        service._public_url = "https://info.ngrok.io"
        service._started_at = "2026-03-13T10:00:00Z"

        tunnel_obj = _make_tunnel_obj("https://info.ngrok.io")
