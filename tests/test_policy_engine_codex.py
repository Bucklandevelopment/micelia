    def test_override_work_to_privacy_high(self, engine):
        engine.set_category_policy("work", "privacy-high")
        decision = engine.evaluate({
            "category": "work",
            "provider_policy": "paid-for-work",
        })
        assert decision.blocked_providers == ["openai", "anthropic"]
        assert decision.prefer_paid is False

    def test_override_to_critical_reviewed(self, engine):
        engine.set_category_policy("personal", "critical-reviewed")
        decision = engine.evaluate({
            "category": "personal",
            "provider_policy": "free-first",
        })
        assert decision.prefer_paid is True
        assert decision.require_different_reviewer is True

    def test_override_does_not_affect_other_categories(self, engine):
        engine.set_category_policy("work", "privacy-high")
        decision = engine.evaluate({
            "category": "note",
            "provider_policy": "free-first",
        })
        assert decision.force_free is True
        assert decision.blocked_providers is None

    def test_override_can_be_replaced(self, engine):
        engine.set_category_policy("work", "privacy-high")
        engine.set_category_policy("work", "free-first")
        decision = engine.evaluate({
            "category": "work",
            "provider_policy": "paid-for-work",
        })
        assert decision.force_free is True

    def test_multiple_overrides(self, engine):
        engine.set_category_policy("work", "critical-reviewed")
        engine.set_category_policy("personal", "privacy-high")
        engine.set_category_policy("note", "budget-cap")

