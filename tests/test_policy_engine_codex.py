class TestBudget:

    def test_defaults(self, budget):
        assert budget.daily_limit_usd == 5.0
        assert budget.monthly_limit_usd == 50.0
        assert budget.spent_today_usd == 0.0
        assert budget.spent_this_month_usd == 0.0
        assert budget.last_reset_date is None
        assert budget.last_reset_month is None

    def test_can_spend_within_daily_limit(self, budget):
        assert budget.can_spend(1.0) is True
        assert budget.can_spend(5.0) is True

    def test_can_spend_at_exact_daily_limit(self, budget):
        """Spending exactly the daily limit should be allowed (<=)."""
        assert budget.can_spend(5.0) is True

    def test_can_spend_exceeds_daily_limit(self, budget):
        assert budget.can_spend(5.01) is False

    def test_can_spend_exceeds_monthly_limit(self):
        b = Budget(daily_limit_usd=100.0, monthly_limit_usd=10.0)
        assert b.can_spend(10.0) is True
        assert b.can_spend(10.01) is False

    def test_can_spend_zero(self, budget):
        assert budget.can_spend(0.0) is True

    def test_record_spend_updates_both_counters(self, budget):
        budget.record_spend(2.0)
        # After auto_reset, last_reset_date is set to today
        assert budget.spent_today_usd == 2.0
        assert budget.spent_this_month_usd == 2.0

    def test_record_spend_multiple(self, budget):
        budget.record_spend(1.0)
        budget.record_spend(1.5)
        budget.record_spend(0.5)
        assert budget.can_spend(2.0) is True
        assert budget.can_spend(2.01) is False

    def test_record_spend_then_can_spend_checks_correctly(self, budget):
        budget.record_spend(4.0)
        assert budget.can_spend(1.0) is True
        assert budget.can_spend(1.01) is False

    def test_auto_reset_daily(self):
        """When last_reset_date is yesterday, daily counter resets."""
        b = Budget()
        yesterday = date.today() - timedelta(days=1)
        b.last_reset_date = yesterday
        b.last_reset_month = date.today().month
        b.spent_today_usd = 4.99
        b.spent_this_month_usd = 10.0

        # can_spend triggers _auto_reset; daily should reset to 0
        assert b.can_spend(5.0) is True
        assert b.spent_today_usd == 0.0  # was reset
        # Monthly should NOT have reset (same month)
        assert b.spent_this_month_usd == 10.0

    def test_auto_reset_monthly(self):
        """When last_reset_month differs, monthly counter resets."""
        b = Budget(daily_limit_usd=100.0, monthly_limit_usd=50.0)
        today = date.today()
        b.last_reset_date = today  # same day, so daily doesn't reset
        # Set to a different month
        different_month = (today.month % 12) + 1
        b.last_reset_month = different_month
        b.spent_today_usd = 2.0
        b.spent_this_month_usd = 49.0

        assert b.can_spend(50.0) is True
        assert b.spent_this_month_usd == 0.0  # was reset

    def test_auto_reset_both_when_none(self):
        """First call with None dates triggers reset for both."""
        b = Budget()
        b.spent_today_usd = 99.0
        b.spent_this_month_usd = 99.0
        assert b.last_reset_date is None
        assert b.last_reset_month is None

        # Calling can_spend triggers _auto_reset which resets because None != today
        assert b.can_spend(5.0) is True

    def test_to_dict_structure(self, budget):
        result = budget.to_dict()
        expected_keys = {
            "daily_limit_usd",
            "monthly_limit_usd",
            "spent_today_usd",
            "spent_this_month_usd",
            "remaining_today_usd",
            "remaining_month_usd",
        }
        assert set(result.keys()) == expected_keys

    def test_to_dict_values_fresh(self, budget):
        result = budget.to_dict()
        assert result["daily_limit_usd"] == 5.0
        assert result["monthly_limit_usd"] == 50.0
        assert result["spent_today_usd"] == 0.0
        assert result["spent_this_month_usd"] == 0.0
        assert result["remaining_today_usd"] == 5.0
        assert result["remaining_month_usd"] == 50.0

    def test_to_dict_after_spending(self, budget):
        budget.record_spend(1.5)
        result = budget.to_dict()
        assert result["spent_today_usd"] == 1.5
        assert result["spent_this_month_usd"] == 1.5
        assert result["remaining_today_usd"] == 3.5
        assert result["remaining_month_usd"] == 48.5

    def test_to_dict_rounds_to_4_decimals(self):
        b = Budget(daily_limit_usd=10.0, monthly_limit_usd=100.0)
        b.record_spend(1.123456789)
        result = b.to_dict()
        assert result["spent_today_usd"] == round(1.123456789, 4)
        assert result["spent_this_month_usd"] == round(1.123456789, 4)

    def test_can_spend_respects_both_limits(self):
        """Must be within BOTH daily AND monthly to allow spend."""
        b = Budget(daily_limit_usd=10.0, monthly_limit_usd=5.0)
        # Daily allows it, but monthly doesn't
        assert b.can_spend(6.0) is False

    def test_custom_limits(self):
        b = Budget(daily_limit_usd=100.0, monthly_limit_usd=500.0)
        assert b.daily_limit_usd == 100.0
        assert b.monthly_limit_usd == 500.0
        assert b.can_spend(100.0) is True
        assert b.can_spend(100.01) is False


