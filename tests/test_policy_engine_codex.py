class TestPolicyEngineIntegration:

    def test_budget_cap_exhaustion_workflow(self):
        """Simulate spending until budget is exhausted."""
        engine = PolicyEngine()
        engine.set_budget(daily=0.015, monthly=100.0)

        # First 3 requests (each estimated at $0.005) should pass
        for _ in range(3):
            decision = engine.evaluate({
                "category": "note",
                "provider_policy": "budget-cap",
            })
            assert decision.budget_available is True
            engine.record_cost(0.005)

        # 4th request: budget exhausted
        decision = engine.evaluate({
            "category": "note",
            "provider_policy": "budget-cap",
        })
        assert decision.budget_available is False
        assert decision.force_free is True

    def test_category_override_then_budget_check(self):
        """Override a category to budget-cap, then exhaust budget."""
        engine = PolicyEngine()
        # Daily limit must be >= estimated cost per request ($0.005)
        engine.set_budget(daily=0.01)
        engine.set_category_policy("work", "budget-cap")

        # Work category now uses budget-cap; should be available initially
        d1 = engine.evaluate({"category": "work", "provider_policy": "paid-for-work"})
        assert d1.prefer_paid is True
        assert d1.budget_available is True

        # Exhaust budget (spend enough so that $0.005 more won't fit)
        engine.record_cost(0.006)
        d2 = engine.evaluate({"category": "work", "provider_policy": "paid-for-work"})
        assert d2.force_free is True
        assert d2.budget_available is False

    def test_privacy_ignores_budget(self):
        """Privacy-high always blocks major providers regardless of budget."""
        engine = PolicyEngine()
        engine.set_budget(daily=1000.0, monthly=10000.0)
        decision = engine.evaluate({
            "category": "personal",
            "provider_policy": "privacy-high",
        })
        assert decision.blocked_providers == ["openai", "anthropic"]
        assert decision.budget_available is True
