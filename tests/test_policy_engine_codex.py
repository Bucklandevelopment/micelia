        assert d_work.require_different_reviewer is True

        d_personal = engine.evaluate({"category": "personal"})
        assert d_personal.blocked_providers == ["openai", "anthropic"]

        d_note = engine.evaluate({"category": "note"})
        assert d_note.budget_available is True


