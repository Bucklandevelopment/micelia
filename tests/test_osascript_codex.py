class TestRunApplescript:
    def test_success_strips_and_builds_command(self, svc):
        with patch.object(
            osa.subprocess, "run", return_value=_completed("  hi \n")
        ) as run:
            out = svc._run_applescript("beep", timeout=12)
        assert out == "hi"
        args, kwargs = run.call_args
        assert args[0] == ["osascript", "-e", "beep"]
        assert kwargs["capture_output"] is True
        assert kwargs["text"] is True
        assert kwargs["timeout"] == 12

    def test_nonzero_raises_osascript_error_with_stderr(self, svc):
        with patch.object(
            osa.subprocess, "run", return_value=_completed("", 1, "  boom  ")
        ):
            with pytest.raises(OSAScriptError) as exc:
                svc._run_applescript("x")
        assert "boom" in str(exc.value)

    def test_timeout_raises(self, svc):
        with patch.object(
            osa.subprocess,
            "run",
            side_effect=subprocess.TimeoutExpired(cmd="osascript", timeout=30),
        ):
            with pytest.raises(OSAScriptError) as exc:
                svc._run_applescript("x", timeout=30)
        assert "timed out" in str(exc.value)

    def test_generic_exception_raises(self, svc):
        with patch.object(osa.subprocess, "run", side_effect=RuntimeError("weird")):
            with pytest.raises(OSAScriptError) as exc:
                svc._run_applescript("x")
        assert "weird" in str(exc.value)


