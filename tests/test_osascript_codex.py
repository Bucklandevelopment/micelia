def _completed(stdout="", returncode=0, stderr=""):
    """Build a fake subprocess.CompletedProcess."""
    return subprocess.CompletedProcess(
        args=[], returncode=returncode, stdout=stdout, stderr=stderr
    )


@pytest.fixture
def svc():
    """OSAScriptService instance built with subprocess.run neutralised.

    Keeps __init__ (which shells out to ``which osascript``) hermetic so the
    suite never depends on the host.
    """
    with patch.object(osa.subprocess, "run", return_value=_completed("", 0)):
        return OSAScriptService()


