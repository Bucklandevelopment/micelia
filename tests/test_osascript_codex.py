"""
Tests for OSAScriptService (app.services.osascript).

Generated by Codex CLI -- comprehensive pytest test suite (Ciclo 26).

The whole module wraps ``subprocess.run`` and parses the resulting stdout, so
it is fully testable without a real macOS host:

* The dedicated helper/verify tests patch ``osa.subprocess.run`` to exercise the
  4 branches of ``_run_applescript`` / ``_run_applescript_file`` and the
  degrade-gracefully behaviour of ``_verify_osascript``.
* The ~30 public methods are tested by patching the instance helper
  (``_run_applescript`` / ``_run_applescript_file``) to return a canned string
  or raise ``OSAScriptError``, which isolates the parse/degradation logic and
  the AppleScript that each method builds.
"""

